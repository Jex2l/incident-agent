"""The investigation loop: webhook intake hands this an alert summary, it
calls tools (via MCP) under hard budgets, and returns schema-validated
output. Every run's full message/tool-call history is saved to traces/.

This is the heart of the whole agent: a plain tool-calling loop (no
multi-agent framework, no planner/executor split - deliberately simple per
the project's own constraints) that alternates between asking the LLM for
the next step and executing whatever tool calls it requests, until the
model produces a final JSON answer or the loop's budgets/retries run out.
"""
import json
import re
import time
from pathlib import Path

import jsonschema

from agent.budgets import Budget, BudgetTracker
from agent.llm import LLMProvider, get_default_provider
from agent.mcp_client import ToolSet
from agent.prompts import SYSTEM_PROMPT
from agent.schema import inconclusive_result, validate_output
from agent.tracing import get_tracer

ROOT = Path(__file__).resolve().parent.parent
TRACES_DIR = ROOT / "traces"
TRACES_DIR.mkdir(exist_ok=True)

# Bounded retries for two distinct failure modes: the model producing
# unparseable or schema-invalid final output (MAX_FORMAT_RETRIES), and the
# LLM provider itself failing transiently - e.g. an Ollama timeout under
# load (MAX_LLM_ERROR_RETRIES). Both are separate from the overall step/
# token/wallclock Budget in budgets.py; these caps stop the loop from
# bouncing between the model and the same bad output forever even while
# the broader budget still has room left.
MAX_FORMAT_RETRIES = 2
MAX_LLM_ERROR_RETRIES = 2
# How much of a tool's raw result gets embedded in the saved trace per call -
# full results can be large; the trace keeps only a preview, while the
# actual message sent back to the model (see `messages.append` below) is
# not truncated, since the model needs the real data to reason over.
TOOL_RESULT_PREVIEW_CHARS = 800

# Matches a ```json ... ``` or bare ``` ... ``` fenced block, in case the
# model wraps its final JSON answer in markdown despite being told not to -
# qwen2.5:7b does this often enough that stripping fences defensively avoids
# burning a format-retry on something trivially recoverable.
_JSON_FENCE_RE = re.compile(r"```(?:json)?\s*(.*?)\s*```", re.DOTALL)


def _try_parse_json(text: str) -> dict | None:
    """Attempt to parse the model's final-turn text as a JSON object,
    stripping a markdown code fence first if present. Returns None (rather
    than raising) on anything that isn't a parseable JSON object, so the
    caller can treat "not JSON" and "wrong JSON shape" uniformly as a
    format-retry trigger.
    """
    text = text.strip()
    m = _JSON_FENCE_RE.search(text)
    if m:
        text = m.group(1).strip()
    try:
        obj = json.loads(text)
    except json.JSONDecodeError:
        return None
    return obj if isinstance(obj, dict) else None


def _tool_result_summary(result: dict) -> str:
    """One-line human-readable summary of a tool result, used to build the
    `fallback_evidence` list that gets attached to an inconclusive_result()
    if the investigation has to bail out before producing a real answer -
    this is what lets a human see "the agent did look at logs and found N
    patterns" even when it never reached a final hypothesis.
    """
    if "error" in result:
        return f"error: {result['error']}"
    for key in ("series", "patterns", "pods", "events", "deployments", "results", "lines"):
        if key in result and isinstance(result[key], list):
            return f"returned {len(result[key])} {key}"
    return "tool call succeeded"


def _validate_tool_args(tool_name: str, arguments, toolset: ToolSet) -> str | None:
    """Pre-validate tool-call arguments against the tool's own JSON schema
    before invoking it, so a malformed call produces a precise error
    message instead of a raw Python exception. Returns an error string, or
    None if arguments are valid."""
    if not isinstance(arguments, dict):
        return "tool arguments must be a JSON object"
    # Look up the tool's own inputSchema (auto-generated by FastMCP from the
    # tool function's signature, surfaced via ToolSet.schemas()) rather than
    # hardcoding per-tool validation here - keeps this generic across all 4
    # tool servers and whatever gets added later.
    schema = next(
        (t["function"]["parameters"] for t in toolset.schemas() if t["function"]["name"] == tool_name),
        None,
    )
    if schema is None:
        return None
    try:
        jsonschema.validate(arguments, schema)
    except jsonschema.ValidationError as e:
        return f"invalid arguments: {e.message}"
    return None


async def investigate(
    alert_summary: dict,
    toolset: ToolSet,
    llm: LLMProvider | None = None,
    budget: Budget | None = None,
    incident_id: str | None = None,
) -> dict:
    """Run one full investigation of an alert and return a schema-valid
    result dict (see agent/schema.py's OUTPUT_SCHEMA).

    This never raises for "the investigation didn't go well" - budget
    exhaustion, bad model output, or LLM provider errors all resolve to a
    normal inconclusive_result() return value, not an exception. Only an
    unexpected bug would propagate out; the caller (agent/webhook.py) still
    wraps this in a try/except as a last-resort safety net so a background
    investigation task can never silently vanish.
    """
    llm = llm or get_default_provider()
    budget = budget or Budget()
    incident_id = incident_id or f"incident-{int(time.time())}"
    tracker = BudgetTracker(budget)
    # Evidence collected so far, kept outside the main message history so it
    # can be attached to an inconclusive_result() even if the loop bails out
    # before the model ever produces a final answer.
    fallback_evidence: list[dict] = []
    # Full record of this investigation, written to traces/<incident_id>.json
    # at the end (success or not) for the trace viewer and for eval scoring.
    trace = {"incident_id": incident_id, "alert": alert_summary, "turns": [], "tool_calls": []}

    # Standard OpenAI-style chat history: system prompt (the investigation
    # method, see agent/prompts.py) followed by the alert as the first user
    # turn. Tool calls/results get appended to this list as the loop runs.
    messages = [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": f"New alert to investigate:\n{json.dumps(alert_summary, indent=2)}"},
    ]

    tracer = get_tracer()
    with tracer.start_as_current_span("investigate") as root_span:
        # This is the root span every llm.chat and tool.call span nests
        # under in the trace viewer - one "investigate" span per incident.
        root_span.set_attribute("incident.id", incident_id)
        root_span.set_attribute("alert.name", str(alert_summary.get("alertname")))
        root_span.set_attribute("alert.namespace", str(alert_summary.get("namespace")))

        def finish(result: dict) -> dict:
            """Common exit path for every way the loop can end (success,
            inconclusive, any kind of bail-out) - always saves the trace and
            records final span attributes, so there's exactly one place
            that has to get this right rather than duplicating it at every
            return site below.
            """
            trace["result"] = result
            trace["budget"] = tracker.summary()
            _save_trace(incident_id, trace)
            root_span.set_attribute("result.status", result.get("status", "unknown"))
            root_span.set_attribute("result.root_cause_label", str(result.get("root_cause_label")))
            root_span.set_attribute("result.confidence", result.get("confidence", 0.0))
            root_span.set_attribute("budget.steps_used", tracker.steps_used)
            root_span.set_attribute("budget.tokens_used", tracker.tokens_used)
            return result

        format_retries = 0
        llm_error_retries = 0
        # The main loop: ask the model for the next move, either execute the
        # tool calls it requested and loop again, or treat a no-tool-calls
        # turn as its attempt at a final answer.
        while True:
            # Checked at the top of every iteration, before spending another
            # LLM call - a budget overrun always produces a real
            # inconclusive_result() with whatever evidence was gathered so
            # far, never just stops silently.
            reason = tracker.exceeded()
            if reason:
                return finish(inconclusive_result(reason, fallback_evidence))

            try:
                response = await llm.chat(messages, tools=toolset.schemas())
            except Exception as e:
                # Transient provider failures (e.g. an Ollama timeout under
                # CPU contention - a real, repeated occurrence on this
                # project's hardware) get a bounded number of retries before
                # giving up for good.
                llm_error_retries += 1
                if llm_error_retries > MAX_LLM_ERROR_RETRIES:
                    return finish(inconclusive_result(f"LLM provider error after retries: {type(e).__name__}: {e}", fallback_evidence))
                continue
            tracker.record_tokens(response.prompt_tokens, response.completion_tokens)
            trace["turns"].append({
                "content": response.content,
                "tool_calls": [{"name": tc.name, "arguments": tc.arguments} for tc in response.tool_calls],
                "prompt_tokens": response.prompt_tokens,
                "completion_tokens": response.completion_tokens,
            })

            if response.tool_calls:
                # The model asked for one or more tools this turn - append
                # its assistant turn (including the requested calls) to the
                # conversation, then execute each one and append a
                # corresponding "tool" role message with the result, exactly
                # as the OpenAI tool-calling convention expects.
                messages.append({
                    "role": "assistant",
                    "content": response.content or "",
                    "tool_calls": [{"function": {"name": tc.name, "arguments": tc.arguments}} for tc in response.tool_calls],
                })
                for tc in response.tool_calls:
                    error = None
                    if tc.name not in toolset.tool_names():
                        error = f"unknown tool '{tc.name}'. Available tools: {toolset.tool_names()}"
                    else:
                        error = _validate_tool_args(tc.name, tc.arguments, toolset)

                    # A hallucinated tool name or invalid arguments becomes a
                    # tool-result error message fed back to the model (so it
                    # can self-correct next turn) rather than a crash or a
                    # skipped turn.
                    tool_result = {"error": error} if error else await toolset.call(tc.name, tc.arguments)
                    trace["tool_calls"].append({
                        "name": tc.name,
                        "arguments": tc.arguments,
                        "result_preview": json.dumps(tool_result)[:TOOL_RESULT_PREVIEW_CHARS],
                    })
                    fallback_evidence.append({"tool": tc.name, "query": tc.arguments, "summary": _tool_result_summary(tool_result)})
                    messages.append({"role": "tool", "content": json.dumps(tool_result)})
                # One "step" = one LLM turn that resulted in tool use,
                # regardless of how many individual tool calls it made -
                # matches how AGENT_MAX_STEPS is described to the model in
                # the system prompt.
                tracker.record_step()
                continue

            # No tool calls this turn -> treat content as a final-answer attempt.
            parsed = _try_parse_json(response.content or "")
            if parsed is None:
                # Not valid JSON at all (possibly after fence-stripping) -
                # tell the model exactly what's wrong and give it another
                # shot, bounded by MAX_FORMAT_RETRIES.
                format_retries += 1
                if format_retries > MAX_FORMAT_RETRIES:
                    return finish(inconclusive_result("model could not produce valid JSON output after retries", fallback_evidence))
                messages.append({"role": "user", "content": "Your last response was not valid JSON. Respond with ONLY the JSON object described in the system prompt - no markdown fences, no other text."})
                continue

            valid, errors = validate_output(parsed)
            if not valid:
                # Valid JSON but the wrong shape (missing field, invalid
                # root_cause_label, etc.) - same bounded-retry treatment,
                # feeding the specific validation errors back so the model
                # has a concrete target to fix rather than guessing again.
                format_retries += 1
                if format_retries > MAX_FORMAT_RETRIES:
                    return finish(inconclusive_result(f"model's output failed schema validation: {errors}", fallback_evidence))
                messages.append({"role": "user", "content": f"Your JSON output failed schema validation: {errors}. Fix it and respond with ONLY the corrected JSON object."})
                continue

            # A valid, schema-conforming final answer - the happy path.
            return finish(parsed)


def _save_trace(incident_id: str, trace: dict):
    """Persist the full investigation record (every turn, every tool call,
    the final result, and budget usage) as pretty-printed JSON so it can be
    loaded by traces/viewer.html or scored by evals/scorer.py.
    `default=str` guards against any non-JSON-native values (e.g. if a tool
    ever returned something like a datetime) ending up in the trace.
    """
    path = TRACES_DIR / f"{incident_id}.json"
    path.write_text(json.dumps(trace, indent=2, default=str))
